const assert = require('assert/strict')
const fs = require('fs/promises')
const path = require('path')
const { spawn } = require('child_process')

async function exerciseInteractions(h) {
  const { dataset, root, env, evaluate, invoke, code, waitFor, close, start, loadedImages, send, releaseMigrationLock } = h
  const config = JSON.parse(await fs.readFile(path.join(root,'browse.json'),'utf8'))
  const prefsPath = path.join(process.env.APPDATA, config.identifier, 'settings.json')
  const legacyPath = path.join(env.APPDATA,'PicPortal','config.json')
  const legacyBytes = await fs.readFile(legacyPath)
  const prefs = async () => JSON.parse(await fs.readFile(prefsPath,'utf8'))
  assert.deepEqual(await prefs(), {}, 'Failed migration must not persist completion marker or partial data')
  assert.equal(await evaluate(`!!document.querySelector('.desktop-status')`), true)
  await releaseMigrationLock()
  const imported = await invoke('preferences_init')
  assert.equal(imported.completed,true);assert.equal(imported.addedProjects,1)
  assert.equal((await prefs()).__picportalMigration.completed,true)
  assert.equal((await prefs()).settings.general.locale,'tw')
  assert.deepEqual(await fs.readFile(legacyPath), legacyBytes)
  assert.equal((await invoke('preferences_init')).addedProjects,0)
  await evaluate(`location.hash='#/about'`)
  await waitFor(()=>evaluate(`!!document.querySelector('.about')`))
  await evaluate(`location.hash='#/projects'`)
  await waitFor(()=>evaluate(`document.querySelectorAll('div.project-card').length===1`))
  await evaluate(`document.querySelector('div.project-card').click()`)
  await waitFor(()=>evaluate(`location.hash.includes('/grid-view')`))
  await evaluate(`globalThis.$viewer=$pinia._s.get('viewer');globalThis.$portal=$pinia._s.get('portalPane')`)
  await loadedImages('.image-item img')
  console.log('PASS actual plugin migration failure, persisted marker ordering, retry/dedup, original config preserved and saved-project opening')

  // Settings UI: change locale, close prompt/cancel, then durable save.
  await evaluate(`location.hash='#/settings'`)
  await waitFor(()=>evaluate(`!!document.querySelector('.general-settings .n-select')`))
  await evaluate(`document.querySelector('.general-settings .n-base-selection').click()`)
  await waitFor(()=>evaluate(`!![...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes('English'))`))
  await evaluate(`[...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes('English')).click()`)
  await waitFor(()=>evaluate(`!!document.querySelector('.save-dialog')`))
  await invoke('plugin:window|close')
  await waitFor(()=>evaluate(`!!document.querySelector('.close-actions')`))
  await evaluate(`document.querySelector('.close-actions button').click()`)
  await waitFor(()=>evaluate(`!document.querySelector('.close-actions')`))
  await evaluate(`document.querySelector('.save-dialog button:last-child').click()`)
  await waitFor(()=>evaluate(`!document.querySelector('.save-dialog')`))
  assert.equal((await prefs()).settings.general.locale,'en')
  assert.equal((await prefs()).extraSetting.keep,true)
  // External modifications reject the write and restore the plugin's cache.
  const currentBytes = await fs.readFile(prefsPath)
  await fs.writeFile(prefsPath, JSON.stringify({...await prefs(),external:true}))
  assert.equal(await code('preferences_set',{key:'settings',value:{general:{locale:'tw',theme:'picportal'},viewer:{portalPanelPosition:'left'},hotkeys:{}}}),'SETTINGS_CHANGED')
  assert.equal((await invoke('preferences_get',{key:'settings'})).general.locale,'en')
  await fs.writeFile(prefsPath,currentBytes)
  console.log('PASS Settings UI save, unsaved close/cancel, awaited persistence and failed-write cache rollback')

  await close();await start()
  assert.equal((await invoke('preferences_get',{key:'settings'})).general.locale,'en')
  assert.equal((await invoke('preferences_get',{key:'projects'})).length,1)
  await invoke('plugin:window|minimize')
  assert.equal(await invoke('plugin:window|is_minimized'),true)
  const second = spawn(path.resolve('src-tauri/target/debug/picportal.exe'),[],{env,cwd:root,windowsHide:true,stdio:'ignore'})
  assert.equal(await new Promise(resolve=>second.once('exit',resolve)),0)
  await waitFor(async()=>!(await invoke('plugin:window|is_minimized')))
  assert.equal(await evaluate(`document.querySelectorAll('#app').length`),1)
  console.log('PASS process restart persistence, second instance exits and restores the minimized primary window')

  // Manual import merges missing fields, preserving current settings and IDs.
  const retryPath = path.join(dataset.root,'retry-config.json')
  const retry = {...JSON.parse(legacyBytes), projects:[...JSON.parse(legacyBytes).projects,{id:'empty-002',name:'新增清單項目',path:path.join(dataset.root,'empty.db'),color:''}],future:{keep:true}}
  await fs.writeFile(retryPath,JSON.stringify(retry))
  console.log(`ACTION import legacy settings: ${retryPath}`)
  await evaluate(`[...document.querySelectorAll('.projects .btn-container button')].find(b=>b.textContent.includes('Electron')).click()`)
  await waitFor(()=>evaluate(`document.querySelectorAll('div.project-card').length===2`),600000)
  assert.equal((await prefs()).projects.length,2)
  assert.equal((await prefs()).settings.general.locale,'en')
  assert.equal((await prefs()).future.keep,true)
  assert.deepEqual(await fs.readFile(legacyPath),legacyBytes)
  console.log('PASS real manual import picker, merged projects/unknown fields and current settings preserved')
  // Edit metadata through the real Vue modal.
  await evaluate(`document.querySelector('div.project-card').dispatchEvent(new MouseEvent('mouseover',{bubbles:true}));document.querySelector('div.project-card button').click()`)
  await waitFor(()=>evaluate(`!!document.querySelector('.n-modal input')`))
  await evaluate(`{const input=document.querySelector('.n-modal input');input.value='已編輯專案';input.dispatchEvent(new Event('input',{bubbles:true}));}`)
  await evaluate(`document.querySelector('.n-modal .n-button--block').click()`)
  await waitFor(async()=>(await prefs()).projects[0].name==='已編輯專案')
  await waitFor(()=>evaluate(`!document.querySelector('.n-modal')`))
  await evaluate(`document.querySelector('div.project-card').click()`)
  await waitFor(()=>evaluate(`location.hash.includes('/grid-view')`))
  await evaluate(`globalThis.$viewer=$pinia._s.get('viewer');globalThis.$portal=$pinia._s.get('portalPane')`)
  await loadedImages('.image-item img')
  await send('Input.dispatchKeyEvent',{type:'keyDown',key:'F2',code:'F2',windowsVirtualKeyCode:113})
  await send('Input.dispatchKeyEvent',{type:'keyUp',key:'F2',code:'F2',windowsVirtualKeyCode:113})
  await waitFor(()=>evaluate('$app.commander.portal'))
  await evaluate('$app.commander.portal=false')
  // Build two legitimate Portal records sharing the already authorized folder.
  await evaluate(`$app.SaveToDB({key:'portals',data:[{id:'group-001',group:'測試群組',childs:[{id:'portal-001',name:'第一',link:${JSON.stringify(dataset.destination)},bg:'',fg:''},{id:'portal-002',name:'第二',link:${JSON.stringify(dataset.destination)},bg:'',fg:''}]}]}).then(()=>$app.SyncDBDataToState({syncKeys:['portals']}))`)
  await evaluate(`document.querySelector('.group-header .flex').click()`)
  await waitFor(()=>evaluate(`document.querySelectorAll('.portal-name').length===2`))
  const sort = await evaluate(`[...document.querySelectorAll('.portal-name')].map(e=>{const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})`)
  await fs.writeFile(path.join(root,'action.json'),JSON.stringify({kind:'sort',points:sort}))
  console.log(`ACTION native Portal sorting: ${JSON.stringify(sort)} (details ${path.join(root,'action.json')})`)
  await send('Input.dispatchMouseEvent',{type:'mousePressed',...sort[1],button:'left',buttons:1,clickCount:1})
  for(let step=1;step<=15;step++) {
    await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:sort[1].x+(sort[0].x-sort[1].x)*step/15,y:sort[0].y,button:'left',buttons:1})
    await new Promise(resolve=>setTimeout(resolve,100))
  }
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',...sort[0],button:'left',clickCount:1})
  await waitFor(()=>evaluate(`$app.dbData.portals[0].childs[0].id==='portal-002'`),600000)
  const normal = JSON.parse(await fs.readFile(path.join(dataset.root,'normal.db'),'utf8'))
  assert.equal(normal.portals[0].childs[0].id,'portal-002')

  // Open the authorized directory in Explorer, then perform a genuine OS drag.
  const dropped = path.join(dataset.destination,'拖入分類')
  await fs.mkdir(dropped)
  await evaluate(`document.querySelector('.group-header .controls-icon button .n-icon').click()`)
  await waitFor(()=>evaluate(`!!document.querySelector('.n-modal .n-tabs-tab')`))
  await evaluate(`[...document.querySelectorAll('.n-modal .n-tabs-tab')].find(e=>/Drop|拖/.test(e.textContent)).click()`)
  await waitFor(()=>evaluate(`!!document.querySelector('.native-drop-zone')`))
  const dropBox = await evaluate(`(()=>{const r=document.querySelector('.native-drop-zone').getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  const boundSession = (await invoke('project_connect',{path:path.join(dataset.root,'normal.db')})).session
  assert.equal(await code('desktop_open_folder',{session:boundSession,path:dataset.root}),'OUTSIDE_SCOPE')
  await invoke('desktop_open_folder',{session:boundSession,path:dataset.destination})
  await evaluate('$app.ConnectProjectDB()')
  await fs.writeFile(path.join(root,'action.json'),JSON.stringify({kind:'drop',directory:dataset.destination,folder:'拖入分類',point:dropBox}))
  console.log(`ACTION OS folder drop: ${dropped} into ${JSON.stringify(dropBox)}`)
  if (process.argv.includes('--skip-os-drop')) {
    await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
    await send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
    await waitFor(()=>evaluate(`!document.querySelector('.n-modal')`))
    console.log('SKIP genuine external folder drop: manual Windows drag required; native fallback sorting, F2 and scoped Explorer opening passed')
  } else {
    await waitFor(()=>evaluate(`document.querySelector('.folder-list')?.textContent.includes('拖入分類')`),600000)
    await evaluate(`document.querySelector('.n-modal .n-button--block').click()`)
    await waitFor(()=>evaluate(`$app.dbData.portals[0].childs.some(p=>p.link===${JSON.stringify(dropped)})`))
    console.log('PASS native fallback Portal sorting, F2 shortcut, scoped Explorer opening and genuine external folder drop')
  }

  // Closing while a conflict is pending waits for the user's resolution.
  const file = path.join(dataset.source,'待處理.png'), dest = path.join(dataset.destination,'待處理.png')
  await fs.copyFile(dataset.image,file);await fs.copyFile(dataset.image,dest)
  await evaluate(`$app.SaveToDB({key:'dockings',data:[{target:${JSON.stringify(file)},portals:['portal-001']}]}).then(()=>$app.SyncDBDataToState({syncKeys:['dockings']}))`)
  await evaluate(`globalThis.$batch=$viewer.StartBatch([{target:${JSON.stringify(file)},destinations:[${JSON.stringify(dest)}]}]);void 0`)
  await waitFor(()=>evaluate(`$viewer.wrap.filesExist.length===1`))
  await invoke('plugin:window|close')
  await waitFor(()=>evaluate(`!!document.querySelector('.close-actions')`))
  await evaluate(`document.querySelector('.close-actions button:last-child').click()`)
  await waitFor(()=>evaluate(`document.querySelector('.layout')?.textContent.includes('完成後將關閉')`))
  assert.equal(await evaluate('$viewer.wrap.wraping'),true)
  await evaluate(`[...document.querySelectorAll('.option-btn')].find(b=>b.textContent.trim()==='忽略').click()`)
  await close()
  assert.equal(JSON.parse(await fs.readFile(path.join(dataset.root,'normal.db'),'utf8')).dockings[0].target,file)
  assert.equal(await fs.stat(file).then(()=>true,()=>false),true)
  console.log('PASS close-after-batch waits for unresolved conflict; skip preserves source and docking; normal shutdown completes')

  await start()
  await evaluate(`location.hash='#/settings'`)
  await waitFor(()=>evaluate(`document.querySelectorAll('.general-settings .n-base-selection').length===2`))
  await evaluate(`document.querySelectorAll('.general-settings .n-base-selection')[1].click()`)
  await waitFor(()=>evaluate(`!![...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes('Naive UI'))`))
  await evaluate(`[...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes('Naive UI')).click()`)
  await evaluate(`[...document.querySelectorAll('.settings .n-menu-item-content')].find(e=>e.textContent.includes('Viewer')).click()`)
  await waitFor(()=>evaluate(`!!document.querySelector('.general-settings .n-button-group')`))
  await evaluate(`document.querySelector('.general-settings .n-button-group button').click()`)
  await invoke('plugin:window|close')
  await waitFor(()=>evaluate(`document.querySelectorAll('.close-actions button').length===3`))
  await evaluate(`document.querySelectorAll('.close-actions button')[1].click()`)
  await close()
  assert.equal((await prefs()).settings.general.theme,'naive')
  assert.equal((await prefs()).settings.viewer.portalPanelPosition,'left')
  await start()
  await evaluate(`location.hash='#/settings'`)
  await waitFor(()=>evaluate(`!!document.querySelector('.general-settings .n-base-selection')`))
  await evaluate(`document.querySelector('.general-settings .n-base-selection').click()`)
  await waitFor(()=>evaluate(`!![...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes('繁體'))`))
  await evaluate(`[...document.querySelectorAll('.n-base-select-option')].find(e=>e.textContent.includes('繁體')).click()`)
  await invoke('plugin:window|close')
  await waitFor(()=>evaluate(`!!document.querySelector('.close-actions')`))
  await evaluate(`document.querySelector('.close-actions button:last-child').click()`)
  await close()
  assert.equal((await prefs()).settings.general.locale,'en')
  await start()
  await evaluate(`location.hash='#/about'`)
  await waitFor(()=>evaluate(`document.querySelector('.about')?.textContent.includes('PicPortal 0.1.0')`))
  // Remove only a list entry through durable IPC; the .db stays untouched.
  const emptyBytes = await fs.readFile(path.join(dataset.root,'empty.db'))
  await invoke('preferences_set',{key:'projects',value:(await prefs()).projects.filter(p=>p.id!=='empty-002')})
  await evaluate(`location.hash='#/projects'`)
  await waitFor(()=>evaluate(`document.querySelectorAll('div.project-card').length===1`))
  assert.deepEqual(await fs.readFile(path.join(dataset.root,'empty.db')),emptyBytes)
  console.log('PASS save-on-close theme/panel, discard-on-close locale, About without Git and list removal preserves project bytes')
  await evaluate(`document.querySelector('.projects .btn-container button').click()`)
  await waitFor(()=>evaluate(`!!document.querySelector('.n-modal input')`))
  await evaluate(`{const input=document.querySelector('.n-modal input');input.value='清單新增測試';input.dispatchEvent(new Event('input',{bubbles:true}));}`)
  const created = path.join(dataset.root,'清單新增.db')
  console.log(`ACTION save new project: ${created}`)
  await evaluate(`document.querySelector('.n-modal .n-form-item:nth-child(2) button').click()`)
  await waitFor(()=>evaluate(`document.querySelectorAll('.n-modal input')[1]?.value===${JSON.stringify(created)}`),600000)
  await evaluate(`document.querySelector('.n-modal .n-button--block').click()`)
  await waitFor(()=>evaluate(`location.hash.includes('/grid-view') && $app.openProject?.name==='清單新增測試'`))
  assert.equal((await prefs()).projects.length,2)
  assert(JSON.parse(await fs.readFile(created,'utf8')).id)
  await close();await start()
  await waitFor(()=>evaluate(`document.querySelectorAll('div.project-card').length===2`))
  assert.equal((await prefs()).projects[1].name,'清單新增測試')
  console.log('PASS native save picker creates complete project and retains its list entry across restart')
}
module.exports = { exerciseInteractions }
